import assert from 'node:assert/strict';
import {CAPACIDADES,dirRun,sanitize,verificarRollback} from '../g038.mjs';
import {simuladorG038} from './simulador_g038.mjs';
assert.deepEqual(CAPACIDADES.casos,['TC-M07-09','TC-M07-10','TC-M07-11','TC-M07-12']);
const rutaProduccion=dirRun({runId:'RUN-G038-V3-20261121-000000'});
assert.match(rutaProduccion,/EvaluacionV3[\\/]Resultados[\\/]RUN-G038-V3-20261121-000000$/);
for(const version of [1,2])assert.throws(()=>dirRun({runId:`RUN-G038-V${version}-20261121-000000`}),/RUN_ID_V3_INVALIDO/);
assert.doesNotMatch(rutaProduccion,/^[^]*[\\/]Resultados[\\/]RUN-G038-V1-/);
assert.deepEqual(sanitize({token:'secreto',nombre_usuario:'Persona',correo_electronico:'x@y.co',valor:'eyJabc.def.ghi'}),{token:'[RESERVADO]',nombre_usuario:'[NOMBRE]',correo_electronico:'[CORREO]',valor:'[JWT]'});
const base=[{id_version_contrato_aaef:3,contrato_version:'2.1',estado:'ACTIVO',fecha_activacion:'2026-11-17T12:00:00Z',fecha_deprecacion:null,fecha_inactivacion:null}];
assert.equal(verificarRollback(base,structuredClone(base)),true);
assert.equal(verificarRollback(base,[{...base[0],fecha_deprecacion:'2026-11-18T12:00:00Z'}]),false);
const sim=simuladorG038();const run='RUN-G038-V3-20261117-000000',headers={'X-Test-Run-Id':run,'X-Sandbox-Secret':'LOCAL'};
await sim.fetcher(`${sim.api}/integracion/contratos`,{method:'GET',headers});
await assert.rejects(sim.fetcher(`${sim.api}/integracion/contratos`,{method:'GET',headers:{...headers,'X-Test-Run-Id':'RUN-G038-V3-20261117-000001'}}),/RUN_AJENO/);
const primera=sim.fetcher(`${sim.api}/integracion/contratos`,{method:'GET',headers});
await assert.rejects(sim.fetcher(`${sim.api}/integracion/contratos`,{method:'GET',headers}),/PETICION_CONCURRENTE_SIMULADOR/);
await primera;
await sim.fetcher(`${sim.api}/test-control/runs/${run}`,{method:'DELETE',headers:{'X-Sandbox-Secret':'LOCAL'}});
const reabierta=await sim.fetcher(`${sim.api}/integracion/contratos`,{method:'GET',headers});
assert.equal(reabierta.headers.get('X-Test-Run-Id'),run);
assert.equal(sim.deleteN,1);
console.log('OK g038_local.test.mjs');
